#!/usr/bin/env python3
"""Generate docs/port-patches.md from a vphone-cli checkout at the pinned revision.

Usage: python3 -I scripts/upstream-patch-inventory.py VPHONE_CLI_CHECKOUT > docs/port-patches.md

Reads the patch set declarations and the standard preset (macOS plutil converts
the preset plist) and assigns each patch a first-release disposition from the
rules below. The rules are a starting classification for FW-04 and FW-08,
which confirm applicability against the actual selected components.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

REVISION = 'b2804adb45a653ff3981f0705108975414dc8d5d'

root = Path(sys.argv[1])
head = subprocess.run(['git', '-C', str(root), 'rev-parse', 'HEAD'], capture_output=True, text=True).stdout.strip()
if head != REVISION:
    sys.exit(f'checkout is at {head or "an unknown revision"}, want {REVISION}')

sets_dir = root / 'VPhoneExecutable/VPhoneCommand/FirmwarePatcher/PatchSets'
preset = root / 'VPhoneExecutable/VPhoneVirtualization/Resources/patches_presets/standard.plist'

IDENT = re.compile(r'[a-z0-9]+(?:[-_][a-z0-9_]+)*-(?:boot|cfw|exp)-[a-z0-9_]+')
CONST = re.compile(r'static let (\w+)\s*=\s*"([^"]+)"')
NAMED = re.compile(r'identifier:\s*(?:"([^"]+)"|(?:[A-Za-z]+\.)?(\w+))')
POSITIONAL = re.compile(r'\w+\(\s*"([^"]+)",\s*"((?:[^"\\]|\\.)*)",', re.S)
TITLE = re.compile(r'title:\s*"((?:[^"\\]|\\.)*)"')


def tier(identifier):
    return next(t for t in ('boot', 'cfw', 'exp') if f'-{t}-' in identifier)


patches = {}
for f in sorted(sets_dir.glob('*.swift')):
    text = f.read_text()
    found = re.search(r'"(com\.vphone\.patchset\.[a-z.]+)"', text)
    if not found or 'Catalog' in f.name:
        continue
    set_id = found.group(1)
    consts = dict(CONST.findall(text))
    for m in NAMED.finditer(text):
        value = m.group(1) or consts.get(m.group(2), '')
        if IDENT.fullmatch(value) and value not in patches:
            title = TITLE.search(text, m.end())
            near = title and title.start() - m.end() < 4000
            patches[value] = (set_id, near and title.group(1) or '')
    for m in POSITIONAL.finditer(text):
        if IDENT.fullmatch(m.group(1)) and m.group(1) not in patches:
            patches[m.group(1)] = (set_id, m.group(2))
    for value in IDENT.findall(text):
        patches.setdefault(value, (set_id, ''))

data = json.loads(subprocess.run(['plutil', '-convert', 'json', '-o', '-', str(preset)],
                                 check=True, capture_output=True, text=True).stdout)
standard_sets = {s['Identifier'] for s in data['PatchSets']}
assert data['Selection']['Kind'] == 'Block'
blocked = set(data['Selection']['Patches'])

OTHER_DEVICE = re.compile(r'homepod|ipad|(^|[-_])tv([-_]|$)|watch|board_audio|pineboard', re.I)
DEFERRED = [
    (re.compile(r'camera|(^|[-_])cam([-_]|$)|facetime|isp_', re.I), 'camera (R12)'),
    (re.compile(r'audio|microphone|sound', re.I), 'audio (R12)'),
    (re.compile(r'gyroscope|accelerometer|attitude', re.I), 'sensors (R12)'),
    (re.compile(r'bluetooth|btvc', re.I), 'virtual Bluetooth / watch pairing'),
    (re.compile(r'debugserver|installcoordination|diskimagesiod', re.I), 'developer tooling'),
    (re.compile(r'metal_cache_reuse|build_version', re.I), 'optional tuning'),
]


def disposition(identifier, set_id):
    if set_id not in standard_sets or identifier in blocked:
        return 'not in upstream standard', ''
    if OTHER_DEVICE.search(identifier):
        return 'other device family', ''
    for pattern, reason in DEFERRED:
        if pattern.search(identifier):
            return 'deferred', reason
    if 'arm64e_x1' in identifier:
        return 'conditional', 'ARM64E_X1 support for userlands built with X1 instructions (upstream names iPhone19,2) on hosts without native X1; FW-04/FW-08 confirm whether 24A446 for iPhone17,3 needs it'
    if set_id == 'com.vphone.patchset.research.board':
        return 'conditional', 'research-board pairings; 23E5207q carries vphone600ap, so FW-04 confirms whether it applies'
    if identifier == 'system-vphoned-boot-install':
        return 'replaced', 'installs the Go guest daemon instead (GUEST-02, FW-07)'
    if identifier == 'system-extensions-boot-gpu_bundle':
        return 'port', 'FW-05, FW-07'
    owner = 'FW-04' if re.match(r'(avpbooter|ibec|ibss|llb|txm|kernel|devicetree|sep)-', identifier) else 'FW-08'
    return 'port', owner


rows = [(set_id, identifier, title, tier(identifier), *disposition(identifier, set_id))
        for identifier, (set_id, title) in patches.items()]
order = ['port', 'replaced', 'conditional', 'deferred', 'other device family', 'not in upstream standard']
rows.sort(key=lambda r: (order.index(r[4]), r[0], r[1]))

print('# Upstream patch inventory')
print()
print(f'Generated by `scripts/upstream-patch-inventory.py` from [vphone-cli `{REVISION[:12]}`]'
      f'(https://github.com/Lakr233/vphone-cli/tree/{REVISION}) (MIT). Do not edit by hand.')
print()
print('The upstream `standard` preset enables every patch of its patch sets except a block list. The disposition')
print('is a rule-based starting point for the iPhone17,3 iOS 27.0.1 (24A446) + cloudOS 26.4 (23E5207q) pair:')
print('FW-04 (boot chain, kernel, device tree, SEP) and FW-08 (userspace and dyld cache) confirm each `port`')
print('entry against the actual selected components and record the result in their patch receipts.')
print()
counts = {d: sum(r[4] == d for r in rows) for d in order}
print('| Disposition | Patches |')
print('| --- | ---: |')
for d in order:
    print(f'| {d} | {counts[d]} |')
print(f'| **total** | **{len(rows)}** |')
for d in order:
    print()
    print(f'## {d[0].upper() + d[1:]}')
    print()
    print('| Patch | Tier | Set | Title | Notes |')
    print('| --- | --- | --- | --- | --- |')
    for set_id, identifier, title, t, disp, note in rows:
        if disp == d:
            print(f'| `{identifier}` | {t} | {set_id.removeprefix("com.vphone.patchset.")} | {title.replace("|", "/")} | {note} |')
